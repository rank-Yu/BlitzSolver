/// <summary>
/// <c>ConquerorPower</c>: powered attacks from a Sovereign Blade deal double damage to the power's
/// owner (<c>ModifyDamageMultiplicative</c>); one stack is lost at its owner's side turn end
/// (<c>CorePowerSupport.TriggerTransientSideTurnEndPowers</c>' decrement list).
/// </summary>
[FlashContent("CONQUEROR_POWER")]
public sealed class ConquerorPower : FlashPowerDef
{
    public override FlashPowerType Type => FlashPowerType.Debuff;

    public override FlashPowerStackType StackType => FlashPowerStackType.Counter;

    public override decimal ModifyDamageMultiplicative(ref FlashExec x, FlashListener self,
        in FlashDamageContext damage, decimal amount)
    {
        if (!damage.HasCardSource || !damage.Props.IsPoweredAttack()
            || damage.CardSource.Id != FlashRegistry.CardId<Cards.Regent.SovereignBlade>())
        {
            return 1m;
        }
        return damage.Target == self.Owner ? 2m : 1m;
    }
}

