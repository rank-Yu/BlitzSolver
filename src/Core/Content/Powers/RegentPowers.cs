/// <summary>
/// <c>ConquerorPower</c>: powered attacks from a Sovereign Blade deal double damage to the power's
/// owner (<c>ModifyDamageMultiplicative</c>); one stack is lost at its owner's side turn end
/// (<c>CorePowerSupport.TriggerTransientSideTurnEndPowers</c>' decrement list).
/// </summary>
[BlitzContent("CONQUEROR_POWER")]
public sealed class ConquerorPower : BlitzPowerDef
{
    public override BlitzPowerType Type => BlitzPowerType.Debuff;

    public override BlitzPowerStackType StackType => BlitzPowerStackType.Counter;

    public override decimal ModifyDamageMultiplicative(ref BlitzExec x, BlitzListener self,
        in BlitzDamageContext damage, decimal amount)
    {
        if (!damage.HasCardSource || !damage.Props.IsPoweredAttack()
            || damage.CardSource.Id != BlitzRegistry.CardId<Cards.Regent.SovereignBlade>())
        {
            return 1m;
        }
        return damage.Target == self.Owner ? 2m : 1m;
    }
}

