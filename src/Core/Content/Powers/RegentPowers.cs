/// <summary>
/// <c>MonarchsGazePower</c>: AfterDamageGiven for a powered attack from its owner applies the amount
/// of <c>MonarchsGazeStrengthDownPower</c> to the damaged enemy
/// (<c>AfterDamageGivenMirrors.HandleMonarchsGazePower</c> → <c>ApplyTemporaryStrengthLoss</c>).
/// </summary>
[BlitzContent("MONARCHS_GAZE_POWER")]
