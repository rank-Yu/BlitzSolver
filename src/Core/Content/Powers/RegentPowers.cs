using CombatSolver.Flash.Kernel;

namespace CombatSolver.Flash.Content.Powers;

/// <summary><c>ChildOfTheStarsPower</c>: block equal to Amount per star spent by its owner.</summary>
[FlashContent("CHILD_OF_THE_STARS_POWER")]
public sealed class ChildOfTheStarsPower : FlashPowerDef
{
    public override FlashPowerType Type => FlashPowerType.Buff;

    public override FlashPowerStackType StackType => FlashPowerStackType.Counter;

    public override void AfterStarsSpent(ref FlashExec x, FlashListener self, int amount)
    {
        if (amount <= 0 || self.Owner != FlashLimits.PlayerOwner)
            return;
        int power = x.B.Powers[self.Index].Amount;
        if (power <= 0)
            return;
        FlashKernel.GainBlock(ref x, self.Owner, (decimal)power * amount, FlashValueProps.Unpowered, fromCard: false);
    }
}

