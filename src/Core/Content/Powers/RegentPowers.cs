/// <summary><c>ChildOfTheStarsPower</c>: block equal to Amount per star spent by its owner.</summary>
[ContentId("CHILD_OF_THE_STARS_POWER")]
public sealed class ChildOfTheStarsPower : PowerDef
{
    public override PowerType Type => PowerType.Buff;

    public override PowerStackType StackType => PowerStackType.Counter;

    public override void AfterStarsSpent(ref Exec x, Listener self, int amount)
    {
        if (amount <= 0 || self.Owner != Limits.PlayerOwner)
            return;
        int power = x.B.Powers[self.Index].Amount;
        if (power <= 0)
            return;
        Kernel.GainBlock(ref x, self.Owner, (decimal)power * amount, ValueProps.Unpowered, fromCard: false);
    }
}

