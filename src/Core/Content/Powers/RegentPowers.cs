/// <summary>
/// <c>StarNextTurnPower</c>: AfterEnergyReset gains its amount of stars and is removed
/// (<c>AfterEnergyResetMirrors.HandleStarNextTurnPower</c>; the removal is skipped when the gain left
/// a pending choice).
/// </summary>
[BlitzContent("STAR_NEXT_TURN_POWER")]
public sealed class StarNextTurnPower : BlitzPowerDef
{
    public override BlitzPowerType Type => BlitzPowerType.Buff;

    public override BlitzPowerStackType StackType => BlitzPowerStackType.Counter;

    public override void AfterEnergyReset(ref BlitzExec x, BlitzListener self)
    {
        BlitzKernel.GainStars(ref x, x.B.Powers[self.Index].Amount);
        if (x.NeedsChoice)
            return;
        BlitzKernel.SetPowerAmount(ref x.B, self.Owner, x.B.Powers[self.Index].Id, 0);
    }
}

/// <summary><c>ArsenalPower</c>: a card generated by its owner grants Amount Strength.</summary>
[BlitzContent("ARSENAL_POWER")]
public sealed class ArsenalPower : BlitzPowerDef
{
    public override BlitzPowerType Type => BlitzPowerType.Buff;

    public override BlitzPowerStackType StackType => BlitzPowerStackType.Counter;

    public override void AfterCardGeneratedForCombat(ref BlitzExec x, BlitzListener self, int position, byte creator)
    {
        if (creator != BlitzLimits.PlayerOwner || self.Owner != BlitzLimits.PlayerOwner)
            return;
        if (!BlitzRegistry.TryPower("STRENGTH_POWER", out ushort strength))
            throw new BlitzUnsupportedException("阿森纳需要力量的 Blitz 定义。");
        BlitzKernel.ApplyPower(ref x, self.Owner, strength, x.B.Powers[self.Index].Amount, self.Owner);
    }
}

/// <summary>
/// <c>ReflectPower</c>: when its owner is hit by a powered attack that dealt blocked damage, the
/// dealer takes that blocked amount as Unpowered damage; one stack is lost at its owner's side turn
/// start (<c>PersistentPowerSupport.TriggerOwnerAfterSideTurnStart</c>).
/// </summary>
[BlitzContent("REFLECT_POWER")]
public sealed class ReflectPower : BlitzPowerDef
{
    public override BlitzPowerType Type => BlitzPowerType.Buff;

    public override BlitzPowerStackType StackType => BlitzPowerStackType.Counter;

    public override void AfterDamageReceived(ref BlitzExec x, BlitzListener self, in BlitzDamageResult result,
        byte dealer)
    {
        if (result.Receiver != self.Owner || result.BlockedDamage <= 0 || !result.Props.IsPoweredAttack()
            || dealer == BlitzLimits.NoOwner)
        {
            return;
        }
        Span<byte> targets = stackalloc byte[1];
        targets[0] = dealer;
        BlitzKernel.Damage(ref x, targets, result.BlockedDamage, BlitzValueProps.Unpowered, self.Owner,
            hasCardSource: false, default);
    }

    public override void OwnerAfterSideTurnStart(ref BlitzExec x, BlitzListener self)
    {
        int amount = x.B.Powers[self.Index].Amount;
        if (amount > 0)
            BlitzKernel.SetPowerAmount(ref x.B, self.Owner, x.B.Powers[self.Index].Id, amount - 1);
    }
}

