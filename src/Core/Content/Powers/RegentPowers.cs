/// <summary>
/// <c>ConquerorPower</c>: powered attacks from a Sovereign Blade deal double damage to the power's
/// owner (<c>ModifyDamageMultiplicative</c>); one stack is lost at its owner's side turn end
/// (<c>CorePowerSupport.TriggerTransientSideTurnEndPowers</c>' decrement list).
/// </summary>
[ContentId("CONQUEROR_POWER")]
public sealed class ConquerorPower : PowerDef
{
    public override PowerType Type => PowerType.Debuff;

    public override PowerStackType StackType => PowerStackType.Counter;

    public override decimal ModifyDamageMultiplicative(ref Exec x, Listener self,
        in DamageContext damage, decimal amount)
    {
        if (!damage.HasCardSource || !damage.Props.IsPoweredAttack()
            || damage.CardSource.Id != Registry.CardId<Cards.Regent.SovereignBlade>())
        {
            return 1m;
        }
        return damage.Target == self.Owner ? 2m : 1m;
    }
}

