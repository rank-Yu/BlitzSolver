/// <summary>
/// <c>BlackHolePower</c>: after its owner gains stars, and after the last play of a manual card series
/// that spent stars (<c>CardPlay.Resources.StarsSpent &gt; 0</c>), deal Amount damage to every hittable
/// enemy as Unpowered (<c>AfterStarsGainedMirrors</c> / <c>AfterCardPlayedMirrors</c>).
/// </summary>
[FlashContent("BLACK_HOLE_POWER")]
public sealed class BlackHolePower : FlashPowerDef
{
    public override FlashPowerType Type => FlashPowerType.Buff;

    public override FlashPowerStackType StackType => FlashPowerStackType.Counter;

    public override void AfterStarsGained(ref FlashExec x, FlashListener self, int amount)
    {
        if (amount <= 0 || self.Owner != FlashLimits.PlayerOwner)
            return;
        DealDamage(ref x, self);
    }

    public override void AfterCardPlayed(ref FlashExec x, FlashListener self, in FlashCardPlayInfo play)
    {
        // CardPlay.Resources.StarsSpent is 0 for auto-plays; IsLastInSeries is the last play index.
        if (x.CurrentPlayIsAutoPlay || x.StarValue <= 0 || self.Owner != FlashLimits.PlayerOwner
            || play.PlayIndex != play.PlayCount - 1)
        {
            return;
        }
        DealDamage(ref x, self);
    }

    private void DealDamage(ref FlashExec x, FlashListener self)
        => FlashCardEffects.DamageAllEnemies(ref x, x.B.Powers[self.Index].Amount, FlashValueProps.Unpowered,
            self.Owner);
}

