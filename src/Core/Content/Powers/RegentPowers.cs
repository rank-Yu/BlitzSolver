using BlitzSolver.Engine;

namespace BlitzSolver.Content.Powers;

/// <summary><c>ChildOfTheStarsPower</c>: block equal to Amount per star spent by its owner.</summary>
[BlitzContent("CHILD_OF_THE_STARS_POWER")]
public sealed class ChildOfTheStarsPower : BlitzPowerDef
{
    public override BlitzPowerType Type => BlitzPowerType.Buff;

    public override BlitzPowerStackType StackType => BlitzPowerStackType.Counter;

    public override void AfterStarsSpent(ref BlitzExec x, BlitzListener self, int amount)
    {
        if (amount <= 0 || self.Owner != BlitzLimits.PlayerOwner)
            return;
        int power = x.B.Powers[self.Index].Amount;
        if (power <= 0)
            return;
        BlitzKernel.GainBlock(ref x, self.Owner, (decimal)power * amount, BlitzValueProps.Unpowered, fromCard: false);
    }
}

