/// <summary>
/// <c>BlackHolePower</c>: after its owner gains stars, and after the last play of a manual card series
/// that spent stars (<c>CardPlay.Resources.StarsSpent &gt; 0</c>), deal Amount damage to every hittable
/// enemy as Unpowered (<c>AfterStarsGainedMirrors</c> / <c>AfterCardPlayedMirrors</c>).
/// </summary>
[ContentId("BLACK_HOLE_POWER")]
public sealed class BlackHolePower : PowerDef
{
    public override PowerType Type => PowerType.Buff;

    public override PowerStackType StackType => PowerStackType.Counter;

    public override void AfterStarsGained(ref Exec x, Listener self, int amount)
    {
        if (amount <= 0 || self.Owner != Limits.PlayerOwner)
            return;
        DealDamage(ref x, self);
    }

    public override void AfterCardPlayed(ref Exec x, Listener self, in CardPlayInfo play)
    {
        // CardPlay.Resources.StarsSpent is 0 for auto-plays; IsLastInSeries is the last play index.
        if (x.CurrentPlayIsAutoPlay || x.StarValue <= 0 || self.Owner != Limits.PlayerOwner
            || play.PlayIndex != play.PlayCount - 1)
        {
            return;
        }
        DealDamage(ref x, self);
    }

    private void DealDamage(ref Exec x, Listener self)
        => CardEffects.DamageAllEnemies(ref x, x.B.Powers[self.Index].Amount, ValueProps.Unpowered,
            self.Owner);
}

