/// <summary>
/// <c>BlackHolePower</c>: after its owner gains stars, and after the last play of a manual card series
/// that spent stars (<c>CardPlay.Resources.StarsSpent &gt; 0</c>), deal Amount damage to every hittable
/// enemy as Unpowered (<c>AfterStarsGainedMirrors</c> / <c>AfterCardPlayedMirrors</c>).
/// </summary>
[BlitzContent("BLACK_HOLE_POWER")]
public sealed class BlackHolePower : BlitzPowerDef
{
    public override BlitzPowerType Type => BlitzPowerType.Buff;

    public override BlitzPowerStackType StackType => BlitzPowerStackType.Counter;

    public override void AfterStarsGained(ref BlitzExec x, BlitzListener self, int amount)
    {
        if (amount <= 0 || self.Owner != BlitzLimits.PlayerOwner)
            return;
        DealDamage(ref x, self);
    }

    public override void AfterCardPlayed(ref BlitzExec x, BlitzListener self, in BlitzCardPlayInfo play)
    {
        // CardPlay.Resources.StarsSpent is 0 for auto-plays; IsLastInSeries is the last play index.
        if (x.CurrentPlayIsAutoPlay || x.StarValue <= 0 || self.Owner != BlitzLimits.PlayerOwner
            || play.PlayIndex != play.PlayCount - 1)
        {
            return;
        }
        DealDamage(ref x, self);
    }

    private void DealDamage(ref BlitzExec x, BlitzListener self)
        => BlitzCardEffects.DamageAllEnemies(ref x, x.B.Powers[self.Index].Amount, BlitzValueProps.Unpowered,
            self.Owner);
}

