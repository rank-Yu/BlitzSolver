/// <summary>
/// <c>StarNextTurnPower</c>: AfterEnergyReset gains its amount of stars and is removed
/// (<c>AfterEnergyResetMirrors.HandleStarNextTurnPower</c>; the removal is skipped when the gain left
/// a pending choice).
/// </summary>
[ContentId("STAR_NEXT_TURN_POWER")]
public sealed class StarNextTurnPower : PowerDef
{
    public override PowerType Type => PowerType.Buff;

    public override PowerStackType StackType => PowerStackType.Counter;

    public override void AfterEnergyReset(ref Exec x, Listener self)
    {
        Kernel.GainStars(ref x, x.B.Powers[self.Index].Amount);
        if (x.NeedsChoice)
            return;
        Kernel.SetPowerAmount(ref x.B, self.Owner, x.B.Powers[self.Index].Id, 0);
    }
}

/// <summary><c>ArsenalPower</c>: a card generated by its owner grants Amount Strength.</summary>
[ContentId("ARSENAL_POWER")]
public sealed class ArsenalPower : PowerDef
{
    public override PowerType Type => PowerType.Buff;

    public override PowerStackType StackType => PowerStackType.Counter;

    public override void AfterCardGeneratedForCombat(ref Exec x, Listener self, int position, byte creator)
    {
        if (creator != Limits.PlayerOwner || self.Owner != Limits.PlayerOwner)
            return;
        if (!Registry.TryPower("STRENGTH_POWER", out ushort strength))
            throw new UnsupportedException("阿森纳需要力量的 Blitz 定义。");
        Kernel.ApplyPower(ref x, self.Owner, strength, x.B.Powers[self.Index].Amount, self.Owner);
    }
}

/// <summary>
/// <c>ReflectPower</c>: when its owner is hit by a powered attack that dealt blocked damage, the
/// dealer takes that blocked amount as Unpowered damage; one stack is lost at its owner's side turn
/// start (<c>PersistentPowerSupport.TriggerOwnerAfterSideTurnStart</c>).
/// </summary>
[ContentId("REFLECT_POWER")]
public sealed class ReflectPower : PowerDef
{
    public override PowerType Type => PowerType.Buff;

    public override PowerStackType StackType => PowerStackType.Counter;

    public override void AfterDamageReceived(ref Exec x, Listener self, in DamageResult result,
        byte dealer)
    {
        if (result.Receiver != self.Owner || result.BlockedDamage <= 0 || !result.Props.IsPoweredAttack()
            || dealer == Limits.NoOwner)
        {
            return;
        }
        Span<byte> targets = stackalloc byte[1];
        targets[0] = dealer;
        Kernel.Damage(ref x, targets, result.BlockedDamage, ValueProps.Unpowered, self.Owner,
            hasCardSource: false, default);
    }

    public override void OwnerAfterSideTurnStart(ref Exec x, Listener self)
    {
        int amount = x.B.Powers[self.Index].Amount;
        if (amount > 0)
            Kernel.SetPowerAmount(ref x.B, self.Owner, x.B.Powers[self.Index].Id, amount - 1);
    }
}

