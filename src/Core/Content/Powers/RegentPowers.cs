/// <summary>
/// <c>StarNextTurnPower</c>: AfterEnergyReset gains its amount of stars and is removed
/// (<c>AfterEnergyResetMirrors.HandleStarNextTurnPower</c>; the removal is skipped when the gain left
/// a pending choice).
/// </summary>
[FlashContent("STAR_NEXT_TURN_POWER")]
public sealed class StarNextTurnPower : FlashPowerDef
{
    public override FlashPowerType Type => FlashPowerType.Buff;

    public override FlashPowerStackType StackType => FlashPowerStackType.Counter;

    public override void AfterEnergyReset(ref FlashExec x, FlashListener self)
    {
        FlashKernel.GainStars(ref x, x.B.Powers[self.Index].Amount);
        if (x.NeedsChoice)
            return;
        FlashKernel.SetPowerAmount(ref x.B, self.Owner, x.B.Powers[self.Index].Id, 0);
    }
}

/// <summary><c>ArsenalPower</c>: a card generated by its owner grants Amount Strength.</summary>
[FlashContent("ARSENAL_POWER")]
public sealed class ArsenalPower : FlashPowerDef
{
    public override FlashPowerType Type => FlashPowerType.Buff;

    public override FlashPowerStackType StackType => FlashPowerStackType.Counter;

    public override void AfterCardGeneratedForCombat(ref FlashExec x, FlashListener self, int position, byte creator)
    {
        if (creator != FlashLimits.PlayerOwner || self.Owner != FlashLimits.PlayerOwner)
            return;
        if (!FlashRegistry.TryPower("STRENGTH_POWER", out ushort strength))
            throw new FlashUnsupportedException("阿森纳需要力量的 Flash 定义。");
        FlashKernel.ApplyPower(ref x, self.Owner, strength, x.B.Powers[self.Index].Amount, self.Owner);
    }
}

/// <summary>
/// <c>ReflectPower</c>: when its owner is hit by a powered attack that dealt blocked damage, the
/// dealer takes that blocked amount as Unpowered damage; one stack is lost at its owner's side turn
/// start (<c>PersistentPowerSupport.TriggerOwnerAfterSideTurnStart</c>).
/// </summary>
[FlashContent("REFLECT_POWER")]
public sealed class ReflectPower : FlashPowerDef
{
    public override FlashPowerType Type => FlashPowerType.Buff;

    public override FlashPowerStackType StackType => FlashPowerStackType.Counter;

    public override void AfterDamageReceived(ref FlashExec x, FlashListener self, in FlashDamageResult result,
        byte dealer)
    {
        if (result.Receiver != self.Owner || result.BlockedDamage <= 0 || !result.Props.IsPoweredAttack()
            || dealer == FlashLimits.NoOwner)
        {
            return;
        }
        Span<byte> targets = stackalloc byte[1];
        targets[0] = dealer;
        FlashKernel.Damage(ref x, targets, result.BlockedDamage, FlashValueProps.Unpowered, self.Owner,
            hasCardSource: false, default);
    }

    public override void OwnerAfterSideTurnStart(ref FlashExec x, FlashListener self)
    {
        int amount = x.B.Powers[self.Index].Amount;
        if (amount > 0)
            FlashKernel.SetPowerAmount(ref x.B, self.Owner, x.B.Powers[self.Index].Id, amount - 1);
    }
}

